// Cuts the hand-drawn frame (src/ornaments/source/websiteVectorOutline.svg) into reusable pieces.
// Writes src/ornaments/hand-drawn.svg (a sprite of <symbol id="hd-…">) and hand-drawn.json (sizes).
// Re-run with `npm run ornaments` after re-exporting the source from Illustrator.
import { readFileSync, writeFileSync } from 'node:fs'

const SOURCE = new URL('../src/ornaments/source/websiteVectorOutline.svg', import.meta.url)
const OUT_SPRITE = new URL('../src/ornaments/hand-drawn.svg', import.meta.url)
const OUT_MANIFEST = new URL('../src/ornaments/hand-drawn.json', import.meta.url)

// All rectangles are [x0, y0, x1, y1] in the source drawing's coordinates (viewBox 0 0 1706.88 1104.58).
// Fixed pieces take every shape centred in their region (allowing TOLERANCE of overhang).
const FIXED = [
  { id: 'corner-medallion', region: [12, 14, 364, 330] },
  { id: 'crest', region: [806, 0, 904, 46] },
  { id: 'jewel', region: [762, 52, 948, 100] },
  { id: 'lattice-cartouche', region: [726, 222, 988, 290] },
  { id: 'lattice-taper', region: [548, 232, 728, 252] },
  { id: 'side-leaf', region: [6, 504, 80, 756] },
  { id: 'corner-flame', region: [14, 896, 132, 1096] },
  { id: 'tailpiece', region: [580, 974, 848, 1088] },
]
// Tiles take every shape crossing their window; the symbol's viewBox clips that to exactly one repeat.
// Window widths are the measured repeat: beads every 52.94, lattice diamonds every 21.81, zigzag every 20.
const TILES = [
  { id: 'tile-bead', window: [544.4, 54.5, 597.34, 64.4] },
  { id: 'tile-lattice', window: [205.45, 237.75, 227.26, 246.35] },
  { id: 'tile-zigzag', window: [115, 1061.6, 135, 1085.3] },
]
// Repeating runs that must not be swallowed by a neighbouring fixed piece.
const EXCLUDE = [
  [114, 236, 560, 248], // lattice run
  [736, 236, 1600, 248], // lattice right of the taper, incl. a stray off-centre X behind the cartouche
  [490, 53, 760, 66], // bead run, left of the jewel
  [950, 53, 1200, 66], // bead run, right of the jewel
  [108, 1060, 362, 1087], // zigzag run
]
const TOLERANCE = 14
// Illustrator packs numbers tightly ("2.19-.13", "1.23.45"), so split on the number shape, not separators.
const NUMBER = /-?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?/gi

const src = readFileSync(SOURCE, 'utf8')
const classStyles = parseClassStyles(src)
const elements = [...src.matchAll(/<(path|line|circle|ellipse|polyline|polygon|rect)\b([^>]*?)\/>/g)].map(
  ([, tag, attrText]) => {
    const attrs = Object.fromEntries([...attrText.matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]))
    return { tag, attrs, bbox: bboxOf(tag, attrs) }
  }
)

const inside = (b, r, t = 0) => b[0] >= r[0] - t && b[1] >= r[1] - t && b[2] <= r[2] + t && b[3] <= r[3] + t
const overlaps = (b, r) => b[0] < r[2] && b[2] > r[0] && b[1] < r[3] && b[3] > r[1]

const assigned = new Set()
for (const piece of FIXED) piece.elements = []
for (const el of elements) {
  if (EXCLUDE.some((zone) => inside(el.bbox, zone))) continue
  const cx = (el.bbox[0] + el.bbox[2]) / 2
  const cy = (el.bbox[1] + el.bbox[3]) / 2
  const piece = FIXED.find(
    ({ region: r }) => cx >= r[0] && cx <= r[2] && cy >= r[1] && cy <= r[3] && inside(el.bbox, r, TOLERANCE)
  )
  if (piece) {
    piece.elements.push(el)
    assigned.add(el)
  }
}
for (const piece of FIXED) piece.viewBox = pad(union(piece.elements.map((el) => el.bbox)), 1)

for (const tile of TILES) {
  const w = tile.window
  // Horizontal tiles: keep shapes that stay within the band vertically (rails, beads, diagonals),
  // not big curves whose bounding box merely overlaps the window.
  tile.elements = elements.filter((el) => overlaps(el.bbox, w) && el.bbox[1] >= w[1] - 2 && el.bbox[3] <= w[3] + 2)
  tile.elements.forEach((el) => assigned.add(el))
  tile.viewBox = w
}

const pieces = [...FIXED.map((p) => ({ ...p, kind: 'fixed' })), ...TILES.map((t) => ({ ...t, kind: 'tile' }))]
const symbols = pieces.map(({ id, viewBox: [x0, y0, x1, y1], elements: els }) =>
  [
    `    <symbol id="hd-${id}" viewBox="${fmt(x0)} ${fmt(y0)} ${fmt(x1 - x0)} ${fmt(y1 - y0)}">`,
    `      <g fill="none" stroke="currentColor" stroke-width=".5" stroke-miterlimit="10">`,
    ...els.map((el) => `        ${serialize(el)}`),
    `      </g>`,
    `    </symbol>`,
  ].join('\n')
)

writeFileSync(
  OUT_SPRITE,
  [
    `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false" style="position:absolute; width:0; height:0; overflow:hidden;">`,
    `  <!-- Generated by scripts/cut-ornaments.mjs from src/ornaments/source/websiteVectorOutline.svg. Do not edit by hand. -->`,
    `  <defs>`,
    ...symbols,
    `  </defs>`,
    `</svg>`,
    ``,
  ].join('\n')
)

const manifest = Object.fromEntries(
  pieces.map(({ id, kind, viewBox: [x0, y0, x1, y1], elements: els }) => {
    const entry = { kind, x: +fmt(x0), y: +fmt(y0), width: +fmt(x1 - x0), height: +fmt(y1 - y0), elements: els.length }
    if (kind === 'fixed') {
      // Silhouette for knocking out lines behind the piece, and the stems that leave it (where
      // generated geometry can attach), both relative to the symbol's top-left corner.
      const local = ([x, y]) => [+(x - x0).toFixed(1), +(y - y0).toFixed(1)]
      entry.hull = convexHull(els.flatMap(outlinePoints)).map(local)
      entry.sockets = socketsOf(els, union(els.map((el) => el.bbox))).map((s) => ({ ...s, at: local(s.at) }))
    }
    return [id, entry]
  })
)
writeFileSync(OUT_MANIFEST, JSON.stringify(manifest, null, 2) + '\n')

for (const [id, m] of Object.entries(manifest)) {
  console.log(`${id.padEnd(18)} ${m.kind.padEnd(6)} ${String(m.width).padStart(7)} x ${String(m.height).padEnd(7)} ${m.elements} shapes`)
}
console.log(`${elements.length - assigned.size} of ${elements.length} shapes left over (straight rules and the mirrored right side)`)

// --- helpers ---------------------------------------------------------------------------------

function parseClassStyles(svg) {
  const styles = {}
  const css = svg.match(/<style>([\s\S]*?)<\/style>/)?.[1] ?? ''
  for (const [, selectors, body] of css.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
    const decls = Object.fromEntries([...body.matchAll(/([\w-]+)\s*:\s*([^;]+);?/g)].map(([, k, v]) => [k, v.trim()]))
    for (const sel of selectors.split(',')) {
      const cls = sel.trim().replace(/^\./, '')
      styles[cls] = { ...styles[cls], ...decls }
    }
  }
  return styles
}

// Illustrator paints with black/white; map those onto the site's ink and paper.
function paintFor(el) {
  const style = { ...(classStyles[el.attrs.class] ?? {}) }
  for (const k of ['fill', 'stroke', 'stroke-width']) if (el.attrs[k] !== undefined) style[k] = el.attrs[k]
  const paint = {}
  const fill = style.fill ?? '#000' // SVG's default fill is black
  if (el.tag !== 'line' && fill !== 'none') {
    if (/^(#fff(fff)?|white)$/i.test(fill)) paint.style = 'fill:var(--paper,#e6dcc3)'
    else paint.fill = 'currentColor'
  }
  if (!style.stroke || style.stroke === 'none') paint.stroke = 'none'
  else {
    const width = parseFloat(style['stroke-width'] ?? '1')
    if (width !== 0.5) paint['stroke-width'] = String(width)
  }
  return paint
}

function serialize(el) {
  const geometry = { ...el.attrs }
  for (const k of ['class', 'id', 'data-name', 'fill', 'stroke', 'stroke-width', 'style']) delete geometry[k]
  const attrs = { ...geometry, ...paintFor(el) }
  return `<${el.tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`
}

function bboxOf(tag, a) {
  const n = (k) => parseFloat(a[k] ?? '0')
  if (tag === 'line') return union([[n('x1'), n('y1'), n('x1'), n('y1')], [n('x2'), n('y2'), n('x2'), n('y2')]])
  if (tag === 'circle') return [n('cx') - n('r'), n('cy') - n('r'), n('cx') + n('r'), n('cy') + n('r')]
  if (tag === 'ellipse') {
    // Illustrator only rotates ellipses about their own centre, so a rotated one fits in its larger radius.
    const [rx, ry] = a.transform ? [Math.max(n('rx'), n('ry')), Math.max(n('rx'), n('ry'))] : [n('rx'), n('ry')]
    return [n('cx') - rx, n('cy') - ry, n('cx') + rx, n('cy') + ry]
  }
  if (tag === 'rect') return [n('x'), n('y'), n('x') + n('width'), n('y') + n('height')]
  const pts = tag === 'path' ? pathPoints(a.d) : pairs((a.points.match(NUMBER) ?? []).map(Number))
  return union(pts.map(([x, y]) => [x, y, x, y]))
}

// End points plus control points: their hull always contains the curve, which is all a bbox needs.
function pathPoints(d) {
  const tokens = d.match(new RegExp(`[a-zA-Z]|${NUMBER.source}`, 'gi')) ?? []
  const pts = []
  let i = 0
  let cmd = ''
  let x = 0
  let y = 0
  let startX = 0
  let startY = 0
  const num = () => parseFloat(tokens[i++])
  while (i < tokens.length) {
    if (/[a-zA-Z]/.test(tokens[i])) cmd = tokens[i++]
    const before = i
    const rel = cmd === cmd.toLowerCase()
    const ox = rel ? x : 0
    const oy = rel ? y : 0
    switch (cmd.toUpperCase()) {
      case 'M':
        x = ox + num()
        y = oy + num()
        startX = x
        startY = y
        pts.push([x, y])
        cmd = rel ? 'l' : 'L' // extra pairs after a moveto are linetos
        break
      case 'L':
      case 'T':
        x = ox + num()
        y = oy + num()
        pts.push([x, y])
        break
      case 'H':
        x = ox + num()
        pts.push([x, y])
        break
      case 'V':
        y = oy + num()
        pts.push([x, y])
        break
      case 'C':
      case 'S':
      case 'Q': {
        const count = cmd.toUpperCase() === 'C' ? 3 : 2
        for (let k = 0; k < count; k++) pts.push([ox + num(), oy + num()])
        ;[x, y] = pts[pts.length - 1]
        break
      }
      case 'A': {
        const rx = num()
        const ry = num()
        i += 3 // rotation, large-arc and sweep flags
        x = ox + num()
        y = oy + num()
        pts.push([x - rx, y - ry], [x + rx, y + ry])
        break
      }
      case 'Z':
        x = startX
        y = startY
        break
    }
    if (i === before && !/[a-zA-Z]/.test(tokens[i] ?? 'Z')) i++ // never stall on a stray number
  }
  return pts
}

// Points that bound a shape: anchors and control points for paths (their hull contains the curve),
// and a ring of points for circles/ellipses.
function outlinePoints(el) {
  const a = el.attrs
  const n = (k) => parseFloat(a[k] ?? '0')
  if (el.tag === 'path') return pathPoints(a.d)
  if (el.tag === 'line') return [[n('x1'), n('y1')], [n('x2'), n('y2')]]
  if (el.tag === 'polyline' || el.tag === 'polygon') return pairs((a.points.match(NUMBER) ?? []).map(Number))
  const [x0, y0, x1, y1] = el.bbox
  const [cx, cy, rx, ry] = [(x0 + x1) / 2, (y0 + y1) / 2, (x1 - x0) / 2, (y1 - y0) / 2]
  return Array.from({ length: 16 }, (_, i) => [cx + rx * Math.cos((i * Math.PI) / 8), cy + ry * Math.sin((i * Math.PI) / 8)])
}

// Monotone chain convex hull.
function convexHull(points) {
  const pts = [...points].sort((p, q) => p[0] - q[0] || p[1] - q[1])
  const cross = (o, a, b) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
  const half = (list) => {
    const out = []
    for (const p of list) {
      while (out.length >= 2 && cross(out[out.length - 2], out[out.length - 1], p) <= 0) out.pop()
      out.push(p)
    }
    return out.slice(0, -1)
  }
  return [...half(pts), ...half([...pts].reverse())]
}

// Open strokes whose end sits on the piece's bounding box and heads out of it: the places where a
// generated line (a rule, a weaving ribbon) should continue the drawing.
function socketsOf(els, [bx0, by0, bx1, by1]) {
  const edges = [
    { edge: 'top', normal: [0, -1], on: ([, y]) => Math.abs(y - by0) < 1.5 },
    { edge: 'bottom', normal: [0, 1], on: ([, y]) => Math.abs(y - by1) < 1.5 },
    { edge: 'left', normal: [-1, 0], on: ([x]) => Math.abs(x - bx0) < 1.5 },
    { edge: 'right', normal: [1, 0], on: ([x]) => Math.abs(x - bx1) < 1.5 },
  ]
  const sockets = []
  for (const el of els) {
    for (const [at, from] of strokeEnds(el)) {
      const len = Math.hypot(at[0] - from[0], at[1] - from[1])
      if (!len) continue
      const dir = [(at[0] - from[0]) / len, (at[1] - from[1]) / len]
      const hit = edges.find((e) => e.on(at) && dir[0] * e.normal[0] + dir[1] * e.normal[1] > 0.94)
      if (!hit) continue
      const weight = parseFloat(paintFor(el)['stroke-width'] ?? '0.5')
      const heading = +((Math.atan2(dir[1], dir[0]) * 180) / Math.PI).toFixed(1)
      sockets.push({ edge: hit.edge, at, heading, weight })
    }
  }
  return sockets.sort((p, q) => p.at[0] - q.at[0] || p.at[1] - q.at[1])
}

// [end point, the point it is heading away from] for both ends of an open stroke.
function strokeEnds(el) {
  const a = el.attrs
  if (el.tag === 'line') {
    const p = [+a.x1, +a.y1]
    const q = [+a.x2, +a.y2]
    return [[p, q], [q, p]]
  }
  if (el.tag === 'polyline') {
    const pts = pairs((a.points.match(NUMBER) ?? []).map(Number))
    return pts.length < 2 ? [] : [[pts[0], pts[1]], [pts[pts.length - 1], pts[pts.length - 2]]]
  }
  if (el.tag !== 'path' || /z/i.test(a.d)) return []
  const seq = pathPoints(a.d) // anchors and control points in drawing order
  const end = seq[seq.length - 1]
  const prev = [...seq].reverse().find((p) => p[0] !== end[0] || p[1] !== end[1])
  const next = seq.find((p) => p[0] !== seq[0][0] || p[1] !== seq[0][1])
  return prev && next ? [[seq[0], next], [end, prev]] : []
}

function pairs(values) {
  const out = []
  for (let i = 0; i + 1 < values.length; i += 2) out.push([values[i], values[i + 1]])
  return out
}

function union(boxes) {
  return boxes.reduce(
    (u, b) => [Math.min(u[0], b[0]), Math.min(u[1], b[1]), Math.max(u[2], b[2]), Math.max(u[3], b[3])],
    [Infinity, Infinity, -Infinity, -Infinity]
  )
}

function pad(b, p) {
  return [b[0] - p, b[1] - p, b[2] + p, b[3] + p]
}

function fmt(v) {
  return String(Math.round(v * 100) / 100)
}
